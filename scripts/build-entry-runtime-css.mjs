#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const RUNTIME_PATH = path.join(ROOT, 'public', 'assets', 'dex-sidebar.js');
const OUTPUT_PATHS = [
  path.join(ROOT, 'public', 'css', 'components', 'dx-entry-runtime.css'),
  path.join(ROOT, 'css', 'components', 'dx-entry-runtime.css'),
  path.join(ROOT, 'docs', 'css', 'components', 'dx-entry-runtime.css'),
];
const CHECK_ONLY = process.argv.includes('--check');

const STYLE_BLOCKS = [
  {
    functionName: 'ensureEntryRuntimeLayoutOverrides',
    label: 'Entry layout',
  },
  {
    functionName: 'ensureEntryButtonPrimitiveOverrides',
    label: 'Entry button primitives',
  },
  {
    functionName: 'ensureDownloadTreeStyles',
    label: 'Download tree',
  },
];

function dedent(value) {
  const lines = String(value || '').replace(/^\n/, '').replace(/\s+$/, '').split('\n');
  const indents = lines
    .filter((line) => line.trim())
    .map((line) => line.match(/^\s*/)?.[0].length || 0);
  const indent = indents.length ? Math.min(...indents) : 0;
  return `${lines.map((line) => line.slice(indent)).join('\n')}\n`;
}

function extractStyleBlock(source, { functionName, label }) {
  const functionMarker = `const ${functionName} =`;
  const functionIndex = source.indexOf(functionMarker);
  if (functionIndex < 0) {
    throw new Error(`Missing ${functionMarker} in ${path.relative(ROOT, RUNTIME_PATH)}`);
  }

  const assignmentMarker = 'style.textContent = `';
  const assignmentIndex = source.indexOf(assignmentMarker, functionIndex);
  if (assignmentIndex < 0) {
    throw new Error(`Missing style template in ${functionName}`);
  }

  const cssStart = assignmentIndex + assignmentMarker.length;
  const cssEnd = source.indexOf('`;\n    document.head.appendChild(style);', cssStart);
  if (cssEnd < 0) {
    throw new Error(`Missing style template terminator in ${functionName}`);
  }

  const css = source.slice(cssStart, cssEnd);
  if (css.includes('${')) {
    throw new Error(`${functionName} contains JavaScript interpolation and cannot be emitted as static CSS`);
  }
  return `/* ${label}. */\n${dedent(css)}`;
}

async function main() {
  const runtimeSource = await fs.readFile(RUNTIME_PATH, 'utf8');
  const blocks = STYLE_BLOCKS.map((block) => extractStyleBlock(runtimeSource, block));
  const output = [
    '/*',
    ' * Generated by scripts/build-entry-runtime-css.mjs from the dex-sidebar',
    ' * compatibility blocks. Do not edit this file directly.',
    ' */',
    '',
    ...blocks,
  ].join('\n');

  if (CHECK_ONLY) {
    const stale = [];
    for (const outputPath of OUTPUT_PATHS) {
      const current = await fs.readFile(outputPath, 'utf8').catch(() => '');
      if (current !== output) stale.push(path.relative(ROOT, outputPath));
    }
    if (stale.length) {
      throw new Error(`Stale generated stylesheet(s): ${stale.join(', ')}`);
    }
    console.log(`verify:entry-runtime-css passed (${OUTPUT_PATHS.length} synchronized stylesheets).`);
    return;
  }

  await Promise.all(OUTPUT_PATHS.map(async (outputPath) => {
    await fs.mkdir(path.dirname(outputPath), { recursive: true });
    await fs.writeFile(outputPath, output, 'utf8');
  }));

  console.log(`build:entry-runtime-css wrote ${OUTPUT_PATHS.length} synchronized stylesheets.`);
}

main().catch((error) => {
  console.error(`build:entry-runtime-css failed: ${error instanceof Error ? error.message : String(error)}`);
  process.exit(1);
});
